package UNO;

/**
 * Enum representing the available colors in an Uno deck.
 * Includes four standard colors and a WILD "color" used for special cards.
 *
 * @author Noor Karabala, Abdullah Hasan, Marwan Alakhras, Yousif Al-Satari
 * @version 3.0 -   Milestone 3
 */

public enum CardColor {

    RED,
    BLUE,
    YELLOW,
    GREEN,
    PINK,
    TEAL,
    ORANGE,
    PURPLE,
    WILD //Used for Wild and Wild Draw Four cards.
}